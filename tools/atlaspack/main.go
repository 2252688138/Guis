// atlaspack 把目录里的散图打包成一张图集（PNG + 坐标表 JSON）。
//
// 用法：
//
//	atlaspack -in assets/sprites -out assets/atlas.png -json assets/atlas.json
//	atlaspack -in assets/sprites -go assets/atlas_gen.go -pkg assets
//
// 支持 -padding（图间留白）、-max（最大边长）、-pot（边长取 2 的幂）。
package main

import (
	"flag"
	"fmt"
	"image"
	_ "image/jpeg"
	"image/png"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"guis/game"
)

func main() {
	in := flag.String("in", "", "包含散图的目录（png/jpg）")
	out := flag.String("out", "atlas.png", "输出图集 PNG")
	meta := flag.String("json", "atlas.json", "输出坐标表 JSON（空字符串 = 不输出）")
	goFile := flag.String("go", "", "可选：生成 Go 常量文件名")
	pkgName := flag.String("pkg", "assets", "生成 Go 常量时的包名")
	padding := flag.Int("padding", 1, "图与图之间的留白像素")
	maxSize := flag.Int("max", 4096, "图集最大边长")
	pot := flag.Bool("pot", false, "边长向上取到 2 的幂")
	flag.Parse()

	if *in == "" {
		fmt.Fprintln(os.Stderr, "atlaspack: 必须指定 -in 目录")
		os.Exit(2)
	}
	imgs, err := loadDir(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "atlaspack:", err)
		os.Exit(1)
	}
	if len(imgs) == 0 {
		fmt.Fprintln(os.Stderr, "atlaspack: 目录里没有可打包的图片:, ", *in)
		os.Exit(1)
	}
	res, err := game.PackAtlas(imgs, game.PackOptions{Padding: *padding, MaxSize: *maxSize, PowerOfTwo: *pot})
	if err != nil {
		fmt.Fprintln(os.Stderr, "atlaspack:", err)
		os.Exit(1)
	}
	if err := savePNG(*out, res.Image); err != nil {
		fmt.Fprintln(os.Stderr, "atlaspack:", err)
		os.Exit(1)
	}

	atlas := game.NewAtlasMap(nil)
	for _, r := range res.Rects {
		atlas.Add(r.Name, r.Rect2())
	}
	if *meta != "" {
		b, err := atlas.Marshal()
		if err != nil {
			fmt.Fprintln(os.Stderr, "atlaspack:", err)
			os.Exit(1)
		}
		if err := os.WriteFile(*meta, b, 0o644); err != nil {
			fmt.Fprintln(os.Stderr, "atlaspack:", err)
			os.Exit(1)
		}
	}
	if *goFile != "" {
		if err := writeGoConsts(*goFile, *pkgName, res); err != nil {
			fmt.Fprintln(os.Stderr, "atlaspack:", err)
			os.Exit(1)
		}
	}
	fmt.Printf("atlaspack: %d 张 -> %s %d×%d 利用率 %.1f%%\n", len(res.Rects), *out, res.W, res.H, res.Used*100)
}

func loadDir(dir string) ([]game.PackImage, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var names []string
	for _, e := range entries {
		if e.IsDir() {
			continue
		}
		switch strings.ToLower(filepath.Ext(e.Name())) {
		case ".png", ".jpg", ".jpeg":
			names = append(names, e.Name())
		}
	}
	sort.Strings(names)
	out := make([]game.PackImage, 0, len(names))
	for _, n := range names {
		f, err := os.Open(filepath.Join(dir, n))
		if err != nil {
			return nil, err
		}
		img, _, err := image.Decode(f)
		f.Close()
		if err != nil {
			return nil, fmt.Errorf("解码 %s: %w", n, err)
		}
		out = append(out, game.PackImage{Name: strings.TrimSuffix(n, filepath.Ext(n)), Image: img})
	}
	return out, nil
}

func savePNG(path string, img image.Image) error {
	if dir := filepath.Dir(path); dir != "" && dir != "." {
		if err := os.MkdirAll(dir, 0o755); err != nil {
			return err
		}
	}
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	return png.Encode(f, img)
}

func writeGoConsts(path, pkg string, res *game.PackResult) error {
	var sb strings.Builder
	sb.WriteString("// Code generated by atlaspack; DO NOT EDIT.\n\n")
	sb.WriteString("package " + pkg + "\n\n")
	sb.WriteString("// Atlas 图集尺寸与帧坐标（与 atlas.png 一致）。\n")
	sb.WriteString(fmt.Sprintf("const (\n\tAtlasW = %d\n\tAtlasH = %d\n)\n\n", res.W, res.H))
	sb.WriteString("// AtlasFrames 帧名 -> [x, y, w, h]。\nvar AtlasFrames = map[string][4]int{\n")
	for _, r := range res.Rects {
		sb.WriteString(fmt.Sprintf("\t%q: {%d, %d, %d, %d},\n", r.Name, r.X, r.Y, r.W, r.H))
	}
	sb.WriteString("}\n")
	return os.WriteFile(path, []byte(sb.String()), 0o644)
}
